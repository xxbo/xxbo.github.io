const assert=require('node:assert/strict'),C=require('../calendar.js');
const now=Date.parse('2026-10-21T04:00:00Z');
const published={id:'zero',date:'2026-10-21',time:'09:30',scheduled_at:'2026-10-21T09:30:00+08:00',country:'中国',title:'CPI',actual:'0',forecast:'0.2',previous:'-0.1',unit:'%',record_type:'indicator'};
const upcoming={...published,id:'future',scheduled_at:'2026-10-21T20:30:00+08:00',time:'20:30',actual:null};
const missing={...published,id:'missing',actual:null,forecast:null};
assert.equal(C.status(published,now),'已公布');assert(!C.upcoming(published,now));
assert.equal(C.status(upcoming,now),'待公布');assert.equal(C.status(missing,now),'公布值未取得');
assert.equal(C.formatValue(published,'actual'),'0 %');assert.equal(C.formatValue(missing,'forecast'),'—');
assert.equal(C.surprise(published).text,'较预期 -0.2 个百分点');assert.equal(C.surprise(missing),null);
assert.equal(C.surprise({...published,actual:'-1',forecast:'-2',unit:'万人'}).text,'较预期 +1 万人');
assert.equal(C.surprise({...published,actual:'4.0–4.5'}),null);
const unknown={id:'date-only',date:'2026-10-21',date_only:true,source_timezone:'Asia/Shanghai',record_type:'indicator',actual:null};
assert(C.scheduleLabel(unknown).includes('北京时间，时刻待定'));assert(!C.scheduleLabel(unknown).includes('美国'));
const rows=[published,upcoming,missing,unknown];
assert.deepEqual(C.select(rows,{mode:'released'},now).map(r=>r.id),['zero']);
assert.equal(C.select(rows,{mode:'today',query:'cpi',country:'中国'},now).length,3);
assert.equal(C.select(rows,{date:'2026-10-20'},now).length,0);
assert.deepEqual(C.future(rows,now).map(r=>r.id),['future','date-only']);
console.log('Calendar checks passed: zero values, result states, units, timezone, surprise and date filters.');
